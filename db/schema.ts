// -------------------------------------------------------- content documents
/**
 * Long-form editorial Markdown — airport guides, country introductions and the
 * static pages — one row per (kind, subject, locale). These used to live as
 * `content/<locale>/{airports,countries,pages}/*.md` files; the database is now
 * the store, so adding a language is an insert instead of a directory of new
 * files, and the app reads documents through lib/content.ts only.
 *
 *   kind='airport'  subject=IATA (upper case)   e.g. ('airport','HKG','zh')
 *   kind='country'  subject=ISO 3166-1 alpha-2  e.g. ('country','US','en')
 *   kind='page'     subject=page slug           e.g. ('page','about','tw')
 *
 * `locale` is intentionally unconstrained, like airport_translations.locale:
 * the app validates against lib/i18n/config.ts, so shipping a language stays a
 * data-only change. The `tw` rows are *derived* from the Chinese source by
 * `scripts/build-hant.mjs` (OpenCC plus `db/terminology/tw-phrases.json`) —
 * never hand-edit them, adjust the phrase list or the generator instead.
 *
 * `updated` is the frontmatter revision date of the document (nullable, shown
 * as "updated on …" and folded into JSON-LD dateModified / sitemap lastmod);
 * `updated_at` is the row's own write timestamp.
 *
 * Round-tripping to files — for backups, review, or handing a locale to a
 * translator — is `scripts/content-export.mjs` / `scripts/content-import.mjs`.
 */
export const contentDocuments = pgTable(
  'content_documents',
  {
    id: serial('id').primaryKey(),
    /** 'airport' | 'country' | 'page' — the check below pins the closed set. */
    kind: text('kind').notNull(),
    /** IATA / country code / page slug, always upper case for codes. */
    subject: text('subject').notNull(),
    /** 'zh' (the authored source) | 'en' | 'tw' (derived) | 'de' | 'fr' | 'it' | any future locale. */
    locale: text('locale').notNull(),
    /** Frontmatter `title` — page heading and metadata title. */
    title: text('title'),
    /** Frontmatter `summary` — meta description and card copy. */
    summary: text('summary'),
    /** Frontmatter `updated` (YYYY-MM-DD), the editorial revision date. */
    updated: date('updated', { mode: 'string' }),
    /** Markdown body, line endings normalised to \n on write. */
    body: text('body').notNull(),
    createdAt: timestamp('created_at', { withTimezone: true, mode: 'date' })
      .notNull()
      .defaultNow(),
    updatedAt: timestamp('updated_at', { withTimezone: true, mode: 'date' })
      .notNull()
      .defaultNow(),
  },
  (t) => [
    unique('content_documents_kind_subject_locale_key').on(t.kind, t.subject, t.locale),
    /** Serves the "every subject in this locale" scans (guide lists, page slugs). */
    index('content_documents_kind_locale_idx').on(t.kind, t.locale),
    check('content_documents_kind_chk', sql`${t.kind} in ('airport', 'country', 'page')`),
  ]
);

// ------------------------------------------------------------------ reports
/**
 * Server-side rollup behind the homepage "statistics" strip. Created by
 * db/custom.sql — `.existing()` tells Drizzle the view is queryable but not
 * its to create or drop.
 */
export const directoryStats = pgView('directory_stats', {
  countryCount: integer('country_count'),
  airportCount: integer('airport_count'),
  terminalCount: integer('terminal_count'),
  gateCount: integer('gate_count'),
}).existing();
