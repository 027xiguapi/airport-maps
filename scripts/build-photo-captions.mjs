/**
 * Keeps the airport photo layer consistent and derives its Traditional Chinese
 * captions — the same "tw is generated, never hand-edited" rule the rest of the
 * site follows (scripts/build-hant.mjs, scripts/_hant.mjs).
 *
 * Inputs, all under public/photos:
 *   manifest.json          machine-written provenance: one entry per downloaded
 *                          file with host, source page and pixel size
 *   captions/<IATA>.json   authored editorial captions, `zh` + `en` only:
 *                          { "<file>.webp": { "zh": "…", "en": "…" } }
 *                          plus optional `"_skip": ["<file>.webp", …]` for
 *                          photos that turned out not to show the airport —
 *                          they stay in the manifest (provenance) but never
 *                          render in the gallery
 *   captions.tw.json       GENERATED by this script — { "<IATA>": { "<file>": "…" } }
 *
 * It validates the three against each other and checks the manifest against the
 * files on disk:
 *   errors   a manifest photo with no file (dead link in the gallery), a photo
 *            file with no manifest entry (nothing may render without a traced
 *            source), a caption for an unknown file, an out-of-date tw file
 *   staged   a photo whose zh caption is not written yet — it does not render
 *            (the caption is the publication gate, lib/airport-photos.ts);
 *            this is the normal state of a freshly downloaded batch
 *   warnings a published photo with no en caption (the en page then shows the
 *            zh line), a file both `_skip`ped and captioned
 *
 * Usage:
 *   node scripts/build-photo-captions.mjs            validate + write captions.tw.json
 *   node scripts/build-photo-captions.mjs --check    validate only; exit 1 on errors
 *   node scripts/build-photo-captions.mjs --photos AAA,ABQ   restrict to codes
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './_env.mjs';
import { toHant } from './_hant.mjs';

const CHECK = process.argv.includes('--check');
const codesArg = process.argv.find((a) => a.startsWith('--photos'));
const ONLY = codesArg
  ? new Set(
      (codesArg.includes('=')
        ? codesArg.split('=')[1]
        : process.argv[process.argv.indexOf(codesArg) + 1]
      )
        ?.split(',')
        .map((c) => c.trim().toUpperCase())
        .filter(Boolean) ?? []
    )
  : null;

const PHOTOS = join(ROOT, 'public', 'photos');
const CAPTIONS = join(PHOTOS, 'captions');
const TW_FILE = join(PHOTOS, 'captions.tw.json');
const JSON_INDENT = 2;

/** Code -> escaped stem for directories/files Windows cannot name (`AUX`). */
const PHOTO_STEMS = (() => {
  try {
    const file = JSON.parse(readFileSync(join(ROOT, 'scripts', 'photo-file-aliases.json'), 'utf8'));
    return Object.fromEntries(
      Object.entries(file).filter(
        ([code, stem]) => /^[A-Z]{3}$/.test(code) && typeof stem === 'string'
      )
    );
  } catch {
    return {};
  }
})();
const STEM_TO_CODE = Object.fromEntries(
  Object.entries(PHOTO_STEMS).map(([code, stem]) => [stem, code])
);
const photoStem = (code) => PHOTO_STEMS[code] ?? code;

const readJson = (path, fallback) => {
  try {
    return JSON.parse(readFileSync(path, 'utf8'));
  } catch {
    return fallback;
  }
};

const manifest = readJson(join(PHOTOS, 'manifest.json'), { airports: {} }).airports ?? {};
const errors = [];
const warnings = [];

/** Authored captions per code, from captions/<IATA>.json; `_skip` lists files
    kept out of the gallery (not really the airport — stock shot, mock-up). */
const captions = new Map();
const skips = new Map();
if (existsSync(CAPTIONS)) {
  for (const name of readdirSync(CAPTIONS).sort()) {
    const match = name.match(/^([A-Z]{3})_?\.json$/);
    if (!match) {
      warnings.push(`captions/${name} ignored (expected <IATA>.json or an escaped stem)`);
      continue;
    }
    const stem = match[1];
    const code = STEM_TO_CODE[stem] ?? stem;
    const rows = readJson(join(CAPTIONS, name), null);
    if (rows === null) {
      errors.push(`captions/${name} is not valid JSON`);
      continue;
    }
    const entries = Object.entries(rows).filter(
      ([key, value]) => !key.startsWith('_') && typeof value === 'object' && !Array.isArray(value)
    );
    captions.set(code, new Map(entries));
    if (Array.isArray(rows._skip)) skips.set(code, new Set(rows._skip));
  }
}

const codes = Object.keys(manifest).sort();
if (codes.length === 0) {
  errors.push('manifest.json lists no airports — nothing to do');
}

const tw = readJson(TW_FILE, {});
let twChanged = false;
let photoCount = 0;
let publishedCount = 0;
let stagedCount = 0;
let skippedCount = 0;

for (const code of codes) {
  if (ONLY && !ONLY.has(code)) continue;
  const entries = manifest[code];
  if (!Array.isArray(entries)) {
    errors.push(`${code}: manifest entry is not a list`);
    continue;
  }
  const dir = join(PHOTOS, photoStem(code));
  const onDisk = new Set(existsSync(dir) ? readdirSync(dir) : []);
  const authored = captions.get(code) ?? new Map();
  const skip = skips.get(code) ?? new Set();
  const twForCode = (tw[code] ??= {});

  for (const entry of entries) {
    const file = entry.file;
    if (!file) {
      errors.push(`${code}: manifest entry without a file name`);
      continue;
    }
    photoCount++;
    if (!onDisk.has(file)) {
      errors.push(`${code}/${file}: in the manifest but missing on disk`);
    }
    onDisk.delete(file);

    // Deliberately excluded photos need no caption; they never render.
    if (skip.has(file)) {
      skippedCount++;
      delete twForCode[file];
      continue;
    }

    const text = authored.get(file);
    if (!text || !text.zh) {
      // The caption is the publication gate: without it the photo stays off
      // the page, so a fresh download batch is staged rather than broken.
      stagedCount++;
      delete twForCode[file];
      continue;
    }
    publishedCount++;
    if (!text.en) {
      warnings.push(`${code}/${file}: published without an en caption — the en page shows the zh line`);
    }
    const traditional = toHant(text.zh);
    if (twForCode[file] !== traditional) {
      twForCode[file] = traditional;
      twChanged = true;
    }
  }

  for (const orphan of [...onDisk].filter((f) => !f.startsWith('.'))) {
    errors.push(`${code}/${orphan}: on disk but not in the manifest (no traced source)`);
  }
  for (const file of authored.keys()) {
    if (!entries.some((entry) => entry.file === file)) {
      errors.push(`${code}/${file}: captioned but not in the manifest`);
    }
  }
  for (const file of skip) {
    if (!entries.some((entry) => entry.file === file)) {
      errors.push(`${code}/${file}: in _skip but not in the manifest`);
    }
    if (authored.has(file)) {
      warnings.push(`${code}/${file}: both _skip and a caption — the caption is unused`);
    }
  }
}

// Codes that have captions but no manifest photos at all.
for (const code of captions.keys()) {
  if (!manifest[code] && !(ONLY && !ONLY.has(code))) {
    errors.push(`captions/${photoStem(code)}.json: no photos for this code in the manifest`);
  }
}

if (twChanged && !CHECK) {
  writeFileSync(TW_FILE, `${JSON.stringify(tw, null, JSON_INDENT)}\n`);
}

const report = [
  `${photoCount} photo(s) across ${(ONLY ? [...ONLY] : codes).length} code(s): ` +
    `${publishedCount} published, ${stagedCount} staged (no zh caption yet), ${skippedCount} skipped by _skip`,
  ...(twChanged && CHECK ? ['captions.tw.json is out of date — run without --check'] : []),
  ...(!twChanged && !CHECK ? ['captions.tw.json is up to date'] : []),
  ...warnings.map((w) => `warning: ${w}`),
  ...errors.map((e) => `error: ${e}`),
];
console.log(report.join('\n'));

if (errors.length > 0 || (CHECK && twChanged)) process.exit(1);
