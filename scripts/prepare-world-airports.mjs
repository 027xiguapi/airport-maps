/**
 * Distills the OurAirports-style world airports CSV into the compact JSON the
 * homepage Leaflet map loads: only airports with an IATA code, scheduled
 * service and type large/medium survive. Coordinates are rounded to four
 * decimals (~10 m) and rows are emitted as arrays to keep the payload small.
 *
 * Source of truth: data/world-airports.csv (kept out of /public — the raw CSV
 * is ~16 MB and has no reason to be deployed).
 *
 * Usage: node scripts/prepare-world-airports.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROOT } from './_env.mjs';

const ROOT_DIR = ROOT;
const SRC = join(ROOT_DIR, 'data', 'world-airports.csv');
const OUT = join(ROOT_DIR, 'public', 'data', 'world-airports.json');

/** Minimal quoted-CSV line parser (the source has commas inside quotes). */
function parseLine(line) {
  const out = [];
  let cur = '';
  let inQuotes = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (inQuotes) {
      if (c === '"') {
        if (line[i + 1] === '"') { cur += '"'; i++; }
        else inQuotes = false;
      } else cur += c;
    } else if (c === '"') inQuotes = true;
    else if (c === ',') { out.push(cur); cur = ''; }
    else cur += c;
  }
  out.push(cur);
  return out;
}

const raw = readFileSync(SRC, 'utf8');
const lines = raw.split(/\r?\n/);
const head = parseLine(lines[0]);
const col = {};
head.forEach((name, i) => (col[name] = i));

const round4 = (v) => Math.round(Number(v) * 10000) / 10000;
const seen = new Map();

for (let i = 1; i < lines.length; i++) {
  if (!lines[i]) continue;
  const c = parseLine(lines[i]);
  const iata = c[col.iata_code];
  const type = c[col.type];
  if (!/^[A-Z]{3}$/.test(iata)) continue;
  if (type !== 'large_airport' && type !== 'medium_airport') continue;
  if (c[col.scheduled_service] !== '1') continue;
  const lat = round4(c[col.latitude_deg]);
  const lng = round4(c[col.longitude_deg]);
  if (!Number.isFinite(lat) || !Number.isFinite(lng)) continue;

  const row = [
    iata,
    c[col.name],
    c[col.municipality] || c[col.name],
    c[col.country_name] || '',
    (c[col.iso_country] || '').toUpperCase(),
    (c[col.continent] || '').toUpperCase(),
    lat,
    lng,
    type === 'large_airport' ? 1 : 0,
  ];
  // One dot per IATA code: large airports win over medium ones.
  const prev = seen.get(iata);
  if (!prev || (!prev[8] && row[8])) seen.set(iata, row);
}

mkdirSync(dirname(OUT), { recursive: true });
const rows = [...seen.values()].sort((a, b) => a[0].localeCompare(b[0]));
writeFileSync(
  OUT,
  JSON.stringify({
    // [iata, name, municipality, country, iso2, continent, lat, lng, isLarge]
    note: 'Filtered from OurAirports-style data: IATA + scheduled service + large/medium type. Generated by scripts/prepare-world-airports.mjs.',
    count: rows.length,
    airports: rows,
  })
);

// Tiny companion module the homepage imports at build time (no runtime fs).
const large = rows.filter((r) => r[8]).length;
const byContinent = {};
for (const r of rows) byContinent[r[5]] = (byContinent[r[5]] ?? 0) + 1;
const META = join(ROOT_DIR, 'lib', 'world-airports-meta.json');
writeFileSync(
  META,
  JSON.stringify(
    { count: rows.length, large, medium: rows.length - large, byContinent },
    null,
    2
  ) + '\n'
);

console.log(`wrote ${OUT}`);
console.log(`wrote ${META}`);
console.log(`airports: ${rows.length} (large ${large}, medium ${rows.length - large}), size ${(readFileSync(OUT).length / 1024).toFixed(0)} KB`);
console.log(`by continent: ${JSON.stringify(byContinent)}`);
