/**
 * Flight numbers for the airport page's flight board.
 *
 * `data/flights.json.gz` is generated by scripts/fetch-flights.mjs from
 * aviability.com's flight sitemaps: one gzipped JSON document holding every
 * `[flight number, airline slug, origin IATA, destination IATA]` record, plus
 * the airline names, per-airport counts and snapshot metadata. lib/flight-store
 * parses it once per process and indexes it lazily, so a board or a flight page
 * reads from memory rather than opening a file per airport.
 *
 * The sitemaps carry no timestamps, so the board shows flight numbers, airlines
 * and routes — never a timetable.
 *
 * Counterpart airports are resolved the way the route map resolves destinations:
 * the bulk world-airports index provides name/city/country (and the German,
 * French, Italian and Korean vocabularies localize them), while airports the
 * directory itself covers override it with their translated record and link to
 * their own page. Airline display names come from the shared snapshot.
 *
 * Server-only: the dataset never reaches the browser.
 */

type WorldAirport = { name: string; city: string; country: string; iso2: string; lat: number; lng: number };

/** Row shape of public/data/world-airports.json (see scripts/prepare-world-airports.mjs). */
type WorldAirportsFile = {
  airports: [string, string, string, string, string, string, number, number, number][];
};

/** Localized counterpart names, reused by the board's search and pager calls. */
const PLACE_CACHE_LIMIT = 24;
const PLACE_CACHE_TTL = 10 * 60 * 1000;

let worldCache: Map<string, WorldAirport> | null = null;

/**
 * Whether an airport has flights in the snapshot. The route page uses this to
 * link to the airport page's flight board only when the board actually renders.
 */
export function hasAirportFlights(iata: string): boolean {
  const code = iata.toUpperCase();
  if (!/^[A-Z]{3}$/.test(code)) return false;
  const data = getFlightDatasetInfo();
  return data != null && Object.hasOwn(data.airports, code);
}

function loadAirlines(): Record<string, string> {
  return getFlightDatasetInfo()?.airlines ?? {};
}

function loadWorldAirports(): Map<string, WorldAirport> {
  if (!worldCache) {
    const file = JSON.parse(
      readFileSync(join(process.cwd(), 'public', 'data', 'world-airports.json'), 'utf8')
    ) as WorldAirportsFile;
    worldCache = new Map(
      file.airports.map(([iata, name, city, country, iso2, , lat, lng]) => [
        iata,
        { name, city, country, iso2, lat, lng },
      ])
    );
  }
  return worldCache;
}

/** Localized names for the bulk airport index, mirroring lib/routes.ts. */
function vocabulary(locale: Locale) {
  if (locale === 'de') return { airport: germanAirportName, city: germanCity, country: germanCountry };
  if (locale === 'fr') return { airport: frenchAirportName, city: frenchCity, country: frenchCountry };
  if (locale === 'it') return { airport: italianAirportName, city: italianCity, country: italianCountry };
  if (locale === 'ko') return { airport: koreanAirportName, city: koreanCity, country: koreanCountry };
  return null;
}

export type FlightPlace = {
  iata: string;
  name: string;
  city: string;
  country: string;
  countryCode: string;
  /** Hand-checked or bulk-index coordinates, when either source has them. */
  lat: number | null;
  lng: number | null;
  /** Site-relative airport page when the directory covers the airport. */
  href?: string;
};

/**
 * Name/city/country for the airports on one board, in the page's locale.
 * The world index covers the flight network broadly; the directory record wins
 * where it exists, and the airport then also links to its own page.
 */
async function resolvePlaces(locale: Locale, codes: string[]): Promise<Map<string, FlightPlace>> {
  const world = loadWorldAirports();
  const vocab = vocabulary(locale);
  const places = new Map<string, FlightPlace>();

  for (const code of codes) {
    const place = world.get(code);
    const facts = getAirportFacts(code);
    places.set(code, {
      iata: code,
      name: place ? (vocab ? vocab.airport(place.name) : place.name) : code,
      city: place ? (vocab ? vocab.city(place.city) : place.city) : '',
      country: place ? (vocab ? vocab.country(place.country) : place.country) : '',
      countryCode: place?.iso2 ?? '',
      lat: facts?.lat ?? place?.lat ?? null,
      lng: facts?.lng ?? place?.lng ?? null,
    });
  }

  // One query for the counterparts the directory itself covers, then their
  // translated record replaces the bulk index (and adds the internal link).
  const coveredCodes = codes.filter((code) => getAirportFacts(code) != null);
  if (coveredCodes.length > 0) {
    const covered = await getAirportsByCodes(locale, coveredCodes);
    for (const airport of covered) {
      const existing = places.get(airport.iata);
      if (!existing) continue;
      existing.name = airport.name;
      existing.city = airport.city;
      existing.country = airport.countryName;
      existing.countryCode = airport.countryCode;
      existing.href = localizedPath(locale, `/airport/${airport.iata}`);
    }
  }

  return places;
}

/** Resolve a handful of airport codes for a flight page, in one DB query. */
export async function getFlightPlaces(
  locale: Locale,
  codes: string[]
): Promise<Map<string, FlightPlace>> {
  return resolvePlaces(locale, [...new Set(codes)]);
}

export function getAirlineName(slug: string): string {
  return loadAirlines()[slug] ?? slug;
}

/** Snapshot date from the flight dataset, e.g. "2026-10-26". */
export function getFlightDataDate(): string | null {
  return getFlightDatasetInfo()?.dataDate ?? null;
}

/**
 * Other flight numbers on the same route, for the flight page's related
 * section. Reads the origin airport's records from the in-memory index, dedupes
 * by number and round-robins across airlines so a single carrier's block of
 * numbers does not fill the list.
 */
export function getRelatedFlightNumbers(
  origin: string,
  destination: string,
  exclude: string,
  limit = 6
): { number: string; airline: string }[] {
  const raw = getAirportFlightRecords(origin);
  if (!raw) return [];
  const names = loadAirlines();
  const target = destination.toUpperCase();
  const seen = new Set<string>();
  const byAirline = new Map<string, { number: string; airline: string }[]>();

  for (const [number, slug, , destinationCode] of raw.departures) {
    if (destinationCode !== target || number === exclude || seen.has(number)) continue;
    seen.add(number);
    const item = { number, airline: names[slug] ?? slug };
    const bucket = byAirline.get(slug) ?? [];
    bucket.push(item);
    byAirline.set(slug, bucket);
  }

  const queues = [...byAirline.values()];
  const out: { number: string; airline: string }[] = [];
  while (out.length < limit && queues.some((queue) => queue.length > 0)) {
    for (const queue of queues) {
      const item = queue.shift();
      if (!item) continue;
      out.push(item);
      if (out.length >= limit) break;
    }
  }
  return out;
}

type PlaceCacheEntry = { at: number; places: Map<string, FlightPlace> };
const placeCache = new Map<string, PlaceCacheEntry>();

/**
 * Cached wrapper around resolvePlaces. A flight board's search and pager calls
 * re-resolve the same airport's counterpart names on every keystroke/page step;
 * the cache keeps that to one query per airport and locale for ten minutes.
 */
async function cachedPlaces(
  locale: Locale,
  iata: string,
  codes: string[]
): Promise<Map<string, FlightPlace>> {
  const key = `${locale}|${iata}`;
  const hit = placeCache.get(key);
  if (hit && Date.now() - hit.at < PLACE_CACHE_TTL) return hit.places;

  const places = await resolvePlaces(locale, codes);
  placeCache.set(key, { at: Date.now(), places });
  if (placeCache.size > PLACE_CACHE_LIMIT) {
    const oldest = placeCache.keys().next().value;
    if (oldest) placeCache.delete(oldest);
  }
  return places;
}

/** Figures shared by the section header, the board and its FAQ. */
export type FlightStats = {
  departures: number;
  arrivals: number;
  airlines: number;
  destinations: number;
};

export function flightStats(raw: AirportFlightRecords): FlightStats {
  const airlines = new Set<string>();
  const destinations = new Set<string>();

  for (const [, slug, , destination] of raw.departures) {
    airlines.add(slug);
    destinations.add(destination);
  }
  for (const [, slug, origin] of raw.arrivals) {
    airlines.add(slug);
    destinations.add(origin);
  }

  return {
    departures: raw.departures.length,
    arrivals: raw.arrivals.length,
    airlines: airlines.size,
    destinations: destinations.size,
  };
}

export type FlightQuery = {
  direction?: FlightDirection;
  page?: number;
  perPage?: number;
  /** Free-text match over flight number, airline, city, country and airport code. */
  query?: string;
};

const DEFAULT_PER_PAGE = 20;

function clamp(value: number, min: number, max: number): number {
  return Math.min(max, Math.max(min, value));
}

/** Case- and accent-insensitive text for the board's free-text search. */
function fold(value: string): string {
  return value.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
}

/**
 * One page of an airport's flight board. Returns null when the airport has no
 * flights in the snapshot (the section then simply does not render). Counts and
 * top airlines describe the whole board, not the returned page.
 */
export async function getAirportFlights(
  locale: Locale,
  iata: string,
  options: FlightQuery = {}
): Promise<AirportFlightBoard | null> {
  const code = iata.toUpperCase();
  const raw = getAirportFlightRecords(code);
  if (!raw || raw.departures.length + raw.arrivals.length === 0) return null;

  // The page omits `direction`: use whichever side of the board actually has
  // flights (a handful of airports are only ever seen as a destination here).
  const direction: FlightDirection =
    options.direction === 'arrivals'
      ? 'arrivals'
      : options.direction === 'departures'
        ? 'departures'
        : raw.departures.length > 0
          ? 'departures'
          : 'arrivals';
  const perPage = clamp(Math.floor(options.perPage ?? DEFAULT_PER_PAGE), 1, 100);
  const list = raw[direction];
  const stats = flightStats(raw);
  const names = loadAirlines();

  // Resolve both directions once: the board's search and pager calls reuse this
  // cache when the reader switches between departures and arrivals.
  const codes = [
    ...raw.departures.map((record) => record[3]),
    ...raw.arrivals.map((record) => record[2]),
  ];
  const places = await cachedPlaces(locale, code, [...new Set(codes)]);
  const query = fold(options.query?.trim() ?? '');

  const otherEnd = (record: FlightRecord) => (direction === 'departures' ? record[3] : record[2]);

  const matches = query
    ? list.filter((record) => {
        const [number, slug] = record;
        const other = otherEnd(record);
        const place = places.get(other);
        const airline = names[slug] ?? slug;
        const haystack = fold(
          `${number} ${airline} ${slug} ${other} ${place?.name ?? ''} ${place?.city ?? ''} ${
            place?.country ?? ''
          }`
        );
        return haystack.includes(query);
      })
    : list;

  const total = matches.length;
  const pageCount = Math.max(1, Math.ceil(total / perPage));
  const page = clamp(Math.floor(options.page ?? 1), 1, pageCount);
  const start = (page - 1) * perPage;

  const rows: AirportFlight[] = matches.slice(start, start + perPage).map((record) => {
    const [number, slug] = record;
    const other = otherEnd(record);
    const place = places.get(other);
    return {
      number,
      airline: names[slug] ?? slug,
      iata: other,
      name: place?.name ?? other,
      city: place?.city ?? '',
      country: place?.country ?? '',
      countryCode: place?.countryCode ?? '',
      airportHref: place?.href,
    };
  });

  return {
    iata: code,
    dataDate: getFlightDataDate() ?? '',
    direction,
    page,
    perPage,
    total,
    pageCount,
    rows,
    counts: {
      departures: stats.departures,
      arrivals: stats.arrivals,
      airlines: stats.airlines,
      destinations: stats.destinations,
    },
  };
}
